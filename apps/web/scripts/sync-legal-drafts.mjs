// Copies the current legal DRAFTS from ../../docs/legal into src/legal-drafts so the
// website shows the same text counsel is reviewing. Run: npm run sync:legal
//
// The first document on each page is the main policy (its "# Title" becomes the
// page <h1>); the rest are appended with headings demoted one level.
// This never marks anything as approved.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const DOCS = fileURLToPath(new URL('../../../docs/legal/', import.meta.url));
const OUT = fileURLToPath(new URL('../src/legal-drafts/', import.meta.url));

const PAGES = {
  privacy: [
    'PRIVACY_POLICY.md',
    'REGIONAL_PRIVACY_SUPPLEMENTS.md',
    'PRIVACY_REQUESTS_AND_DELETION.md',
    'DATA_RETENTION_SUMMARY.md',
    'VENDOR_AND_SUBPROCESSOR_LIST.md',
  ],
  terms: [
    'TERMS_OF_SERVICE.md',
    'SUBSCRIPTION_TERMS.md',
    'REFUND_AND_CANCELLATION_POLICY.md',
    'AI_NUTRITION_AND_RECIPE_DISCLAIMER.md',
  ],
};

export function toSection(markdown, { isMain }) {
  const lines = markdown.replace(/\r\n/g, '\n').trim().split('\n');
  const title = lines[0].match(/^# (.+)$/)?.[1];
  if (!title) throw new Error(`Expected "# Title" on the first line, got: ${lines[0]}`);
  const body = lines.slice(1).map((line) => (isMain ? line : line.replace(/^(#{2,5}) /, '#$1 ')));
  return { title, text: isMain ? body.join('\n') : [`## ${title}`, ...body].join('\n') };
}

export function readVersion(markdown) {
  const version = markdown.match(/^- Version: (.+)$/m)?.[1]?.trim();
  if (!version) throw new Error('Missing "- Version:" line');
  return version;
}

async function buildPage(name, files) {
  const sources = await Promise.all(files.map((file) => readFile(DOCS + file, 'utf8')));
  const sections = sources.map((md, index) => toSection(md, { isMain: index === 0 }));
  const frontmatter = [
    '---',
    `title: ${JSON.stringify(sections[0].title)}`,
    `version: ${JSON.stringify(readVersion(sources[0]))}`,
    `sources: ${JSON.stringify(files)}`,
    '---',
    '',
    '<!-- Generated by scripts/sync-legal-drafts.mjs from docs/legal. Do not edit by hand. -->',
    '',
  ];
  await writeFile(`${OUT}${name}.md`, `${frontmatter.join('\n')}${sections.map((s) => s.text).join('\n\n')}\n`);
  console.log(`Wrote src/legal-drafts/${name}.md from ${files.length} draft(s)`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [name, files] of Object.entries(PAGES)) await buildPage(name, files);
}
